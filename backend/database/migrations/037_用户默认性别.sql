-- FP-15a（需求 #16「对象性别驱动选中框蓝/粉」的数据层前置）：`用户`.`默认性别` 的**唯一补列路径**
--
-- 旧口径：`默认性别` 只写在两份建表脚本里（database/000_baseline.sql:25、backend/database/init.sql:19），
--         全库**没有任何补列迁移**（FP-22f 实测并把这条分叉登记成账本用例）⇒ 只有"空卷首启新建的库"
--         天然带着这一列；早于它的存量库无论重放多少条迁移都补不上，按名读写该列即
--         Postgres 42703 undefined_column —— 与迁移 022 记录的是同一失败模式（那里是 管理端按
--         运营/审核员 三列查询把每个管理接口打成 500）。消费点现在就有两处：
--         backend/src/services/认证.ts:60（出参 mo_ren_xing_bie 映射）与 :519（设置默认性别 UPDATE）。
-- 新口径：本迁移是该列的正式增量依据，与 baseline 建表语句构成「两方一致」——
--         新库由 `000_baseline.sql` 直接建出该列、老库由本迁移补齐，两条起点收敛到同一列集合。
--         该不变量由两个测试双向钉住：backend/scripts/__tests__/迁移037用户默认性别.test.ts（真库实跑两种起点）
--         与 frontend/src/__tests__/FP22fSQL列集合三方一致.test.ts（静态列集合，口径已按 L-07 裁定改为两方）。
--         注意：`backend/database/migrations/` 下**已应用**的迁移文件字节级不可改（校验和台账，L-09），
--         所以补列只能新增本文件，不能回改 baseline 时代的任何既有迁移。
--
-- 值域（**不新造第二套值域字面量**，与仓内既有真源同源）：
--   性别写法的全库唯一识别口是 backend/src/utils/性别.ts（FP-13）：六种外部写法 → 内部规范形态 nan/nv
--   → 用户资料形态。本列落的是**用户资料形态**（utils/性别.ts:109 性别用户形态，由 内部转用户形态 单向
--   映射；前端 types/index.ts:23 的 XingBie 即该类型，账号与安全.vue 的默认性别单选也是 male/female）。
--   utils/性别.ts:104-108 已写明「仅 用户.默认性别 列与前端资料向导使用；该列不在迁移 024 范围内」
--   ⇒ 本列不得被洗成 nan/nv，否则会把 FP-13 的形态边界重新搅浑。
--   同一张表的另两列**并不同值域**（实测，勿再合并理解）：`目标性别` 由 services/角色生成.ts:205/323-325/711
--   以**内部规范形态** nan/nv 落库；`性别` 列后端只有 注销 时置 NULL（services/账号注销.ts:97），
--   全库未找到写入者。⇒ 这既是本列不挂 CHECK 的理由之一（同族三列不同值域，挂一套 CHECK 等于新造规则），
--   也是交回 FP-15b/FP-20 的既有分叉（消费 用户.性别 时不得假设它与 默认性别 同一套写法）。
-- 值域字面量: 'male' | 'female'
--   NULL = 该用户从未设置过默认性别（需求 #16 的「无默认性别」分支判的正是这个 NULL，FP-15b 消费）。
--   写入侧卡口已在位：services/认证.ts::setMoRenXingBie 先过 解析性别 + 内部转用户形态，
--   不可识别写法在应用层就回 400（huoQuFanYi('anQuan','shenFenBuHeFa')），不落库。
--
-- 为什么**不加 CHECK**（"与既有 `性别` 列同族同源"按同族执行，而非自造一套约束形态）：
--   ① 同族：`性别`/`目标性别` 两列在两份建表脚本与全部迁移里都是裸 VARCHAR(10)、可空、无默认值、
--      无 CHECK（本库对 CHECK 的既有用法是 024 那类「全域归一 + 二值不变量」的表，不是用户资料列）。
--      单给 默认性别 挂 CHECK 会让同族三列的约束形态彼此分叉，属新造第二套规则。
--   ② 一挂就造假：init.sql 按 L-07 裁定**只准改注释、禁改 SQL 语义** ⇒ CHECK 只能落在 baseline 一侧，
--      两份建表脚本当场重新分叉，正是本单要收的旧账。
--   ③ 存量风险不对称：ADD CONSTRAINT 会校验全部历史行，任何历史写法（含空串）都会让整条迁移
--      在**所有**环境硬失败并打挂启动（entrypoint.sh:16-19 迁移不通即中止启动），
--      收益却低于应用层已有的白名单卡口。库侧值域不变量的穷尽治理归 FP-20，不在本单擅自扩面。
--   ⇒ 列定义与 `性别` 列逐 token 同族（VARCHAR(10) 可空无默认），由测试用 baseline 里 `性别` 的
--     实际定义串作比对基准，任一侧漂移即红。
--
-- 删除语义（显式定案）：
--   ① 本列是 用户 行自带的标量偏好，**不被任何表引用**（无外键、无级联、无索引依赖）：
--      删用户行 ⇒ 值随行消失，不影响他表；账号注销已把它显式置 NULL（services/账号注销.ts:99），
--      本迁移不改动该路径，也不得因本迁移而失败。
--   ② 本迁移只前进不回滚（与 032/033/035 同族，库内无 DOWN 脚本）：纯增量 ADD COLUMN IF NOT EXISTS，
--      无 UPDATE / 无 DELETE / 无 DROP / 不改任何既有列的类型、约束、默认值，也不触碰 用户 以外的表。
--      撤销本迁移只能由人工显式 `ALTER TABLE "用户" DROP COLUMN`，不存在任何自动回退路径。
--   ③ 幂等（两种起点都由真库用例实测）：列已在位的库整条 ADD COLUMN 跳过、重复执行零变更；
--      列缺失的老库补齐后再次执行同样零变更。
--
-- 同批收口 `图片授权`（FP-22f 交回项 + L-07 的 SQL 一致性旧账②）：它与 默认性别 是同一病灶——
--   只写在 database/000_baseline.sql:34，init.sql 与全部迁移都没有 ⇒ 新库有、老库永远补不上，
--   按名列读写即 42703。此处按 baseline 的原样定义（BOOLEAN DEFAULT FALSE）幂等补齐；
--   不另立迁移编号：同一根因、同一「baseline 有而迁移链无」的列族，拆成两个文件只会给台账
--   多一条无信息增量的记录（036 已预留给 FP-21 的好友侧两列，编号也不允许它占用）。

ALTER TABLE "用户" ADD COLUMN IF NOT EXISTS "默认性别" VARCHAR(10);
ALTER TABLE "用户" ADD COLUMN IF NOT EXISTS "图片授权" BOOLEAN DEFAULT FALSE;

COMMENT ON COLUMN "用户"."默认性别" IS '用户资料形态性别偏好，值域 male/female（唯一真源 backend/src/utils/性别.ts 的 性别用户形态）；NULL = 未设置。仅作资料向导第一步的预选，不参与任何角色/对象性别判定';

COMMENT ON COLUMN "用户"."图片授权" IS '是否授权站点使用其上传图片；定义与 database/000_baseline.sql:34 逐 token 一致（BOOLEAN DEFAULT FALSE）';

-- FP-10 缺陷9（QQ 式图文混排）后端半边：**增量式**顺序化消息内容块
-- 旧口径：一条消息只能表达「一段文字 + 至多一个媒体」——"内容" 存那段文字、"媒体ID" 存那一个媒体，
--         用户在一条消息里「文字 / 图片 / 文字 / 图片」的先后位置没有任何地方可存
--         （这也是粘贴图片只能"贴图即直发"的结构性根因，见 PROGRESS F6/F7）。
-- 新口径："内容块" 承载**有序**块数组，元素形态（JSON 键沿用出参的拼音下划线风格）：
--           { "lei_xing": "wenzi",  "nei_rong": "文字…" }
--           { "lei_xing": "tupian", "mei_ti_id": "媒体文件ID" }
--         "内容" 与 "媒体ID" 自本迁移起降级为**兼容投影**，由 services/消息内容块.ts 单点派生：
--           "内容"   = 文字块按序拼接、图片块以既有占位符 [图片] 内联（顺序保真）
--           "媒体ID" = 首个图片块引用的媒体
--         目的是让所有现存读取方（AI 上下文渲染、复盘、军师、战绩、出参收口、旧客户端）
--         零改动即继续读到顺序正确、文本完整的消息。
-- 命名撞车说明：本列是**消息**的内容块（用户编辑出的图文顺序）；`utils/DeepSeek客户端.ts` 的
--         "内容块"（DuiHuaKuai）是**喂给模型的**请求体分片。两者不同物，代码里分别自称
--         XiaoXiKuai 与 DuiHuaKuai，禁互相赋值。
-- 历史行零改写：本列 NULL 即「旧数据 / 旧客户端」，读取侧按 内容 + 媒体ID + 类型 反构等价块数组，
--         出参文本与改造前逐字相同（向后兼容不变量，由 FP10 真库测试钉住）。
-- 纯增量：无 UPDATE / 无 DELETE / 不改任何既有列的类型、约束、默认值；可重复执行。

ALTER TABLE "消息" ADD COLUMN IF NOT EXISTS "内容块" JSONB;

COMMENT ON COLUMN "消息"."内容块" IS '有序消息内容块数组 [{lei_xing:"wenzi",nei_rong},{lei_xing:"tupian",mei_ti_id}]；NULL = 旧数据或旧客户端，读取侧由 内容+媒体ID+类型 反构（不回填历史行）';
COMMENT ON COLUMN "消息"."内容" IS '兼容投影：文字块按序拼接、图片块以 [图片] 占位内联；有 内容块 的行由 消息内容块.ts 派生写入，无 内容块 的行仍是唯一真源';
COMMENT ON COLUMN "消息"."媒体ID" IS '兼容投影：首个图片块引用的媒体（FK → 媒体文件 ON DELETE SET NULL）；读取方不得据此假设"一条消息只有一张图"';

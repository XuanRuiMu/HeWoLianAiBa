-- 存量角色回复延迟压缩：旧画像区间 8000~12000 毫秒等比压缩到 1000~3000 毫秒。
-- 映射：8000→1000，12000→3000，线性压缩并四舍五入；越界钳制到 [1000,3000]。
-- 幂等写法，可重复执行。

UPDATE "角色"
SET "回复延迟毫秒" = GREATEST(1000, LEAST(3000, ROUND(("回复延迟毫秒" - 8000) * 2000.0 / 4000.0 + 1000)))
WHERE "回复延迟毫秒" IS NOT NULL AND ("回复延迟毫秒" < 1000 OR "回复延迟毫秒" > 3000);

ALTER TABLE "角色" ALTER COLUMN "回复延迟毫秒" SET DEFAULT 2000;

/**
 * 时区（第十七轮新增）。
 *
 * ## 为什么需要
 *
 * 用户定稿：「AI 对象大部分都是中国人，他们不会在半夜、凌晨聊天发消息；
 * 如果 AI 人设是**美国留学**的，那么时间（以及环境、习惯等）就应该按照他的情况去执行。」
 *
 * 也就是说：**时间必须是「角色所在地的当地时间」，不是服务器时间。**
 * 中国用户与北美东部差 12–15 小时（夏令时）—— 同一时刻，
 * 一个在睡，另一个在赶 due。
 *
 * ## 当前的真实状态（必须说清，不能装作完成）
 *
 * ⚠️ **本模块目前只覆盖国内城市 = 偏移 0。**
 *   `角色配置.ts::chengShiKu` 的 16 个城市全在境内，人物**无法被生成在境外**，
 *   所以还没有真实的跨时区场景。
 *   本模块先按「可扩展」写好：一旦城市库加入境外，这里加一行偏移即可，
 *   `AI回复调度器.当地现在小时()` 不用改。
 *
 *   夏令时不做自动推算 —— 依赖对象数据库的 IANA 时区名（`Asia/Shanghai`）才可靠，
 *   而当前表里存的是中文城市名，硬算夏令时会引入「算错了且没人发现」的静默错误。
 *   故境外偏移走**显式配置**，不做隐式推断。
 */

/** 境外/跨时区城市 → 相对 UTC 的**固定**偏移小时数（不做夏令时推断，见头注） */
const GUO_WAI_SHI_CHA: Record<string, number> = {
  // ── 北美（对照北京 UTC+8，标准时差） ──
  '纽约': -5, '洛杉矶': -8, '旧金山': -8, '西雅图': -8, '波士顿': -5,
  '芝加哥': -6, '多伦多': -5, '温哥华': -8, '休斯顿': -6, '迈阿密': -5,
  '西雅图/纽约': -5,
  // ── 东亚 ──
  '东京': 9, '首尔': 9, '香港': 8, '澳门': 8,
  // ── 欧洲 ──
  '伦敦': 0, '巴黎': 1, '柏林': 1, '罗马': 1, '莫斯科': 3, '悉尼': 10, '墨尔本': 10,
  // ── 其他 ──
  '新加坡': 8, '曼谷': 7, '迪拜': 4,
}

/** 境内城市：偏移恒为 0 */
const JING_NEI_CHENG_SHI = new Set([
  '北京', '上海', '广州', '深圳', '杭州', '成都', '武汉', '西安',
  '南京', '重庆', '天津', '苏州', '长沙', '青岛', '厦门',
])

/**
 * 城市 → 相对 UTC 的固定偏移小时。
 *
 * ⚠️ **返回 0 而不是 null**（初版注释写「返回 0」而代码 `return null`，实测被单测抓到）：
 *   调用方是「按当地小时算作息」，拿不到偏移时必须有个确定值。
 *   返回 0 = 按境内处理，是**已知错误但可预期**的降级；
 *   返回 null 会让调用方各自决定降级策略，反而不可控。
 *   空城市名同样返回 0（此时角色信息不全，按境内最安全）。
 */
export function duShiChaXiaShi(chengShi: string): number {
  // 全局覆盖优先（自测用），生产为空即不影响任何城市
  const quanQiu = duPeiZhiShiCha()
  if (quanQiu !== 0) return quanQiu
  const zheng = (chengShi || '').trim()
  if (!zheng) return 0
  if (JING_NEI_CHENG_SHI.has(zheng)) return 0
  // 城市名可能带后缀（「纽约(New York)」「西雅图/纽约」），做包含匹配
  for (const [cheng, cha] of Object.entries(GUO_WAI_SHI_CHA)) {
    if (zheng.includes(cheng)) return cha
  }
  return 0
}

/**
 * 运营可配的**全局固定偏移**（灰度/自测用；格式 `XING_SHI_CHA=-5`，取值 −12..14）。
 *
 * ⚠️ 这是**全库覆盖**：一旦设置，城市表全部失效。存在的意义是——
 *   自测时不用改代码就能把全服时间整体拨过去，验证作息链路。
 *   ⚠️ 生产必须为空（未设置 ⇒0），否则会把境内 16 城也一起拨走。
 */
export function duPeiZhiShiCha(): number {
  const yuan = Number((process.env.XING_SHI_CHA || '').trim())
  if (Number.isFinite(yuan) && yuan >= -12 && yuan <= 14) return yuan
  return 0
}

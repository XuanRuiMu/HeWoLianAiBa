export type FanYiFenLei = keyof typeof fanYi
export type FanYiJian<T extends FanYiFenLei> = keyof (typeof fanYi)[T]

export function huoQuFanYi<T extends FanYiFenLei>(
  fenLei: T,
  jian: FanYiJian<T>,
): string {
  return fanYi[fenLei][jian] as string
}

/** 带占位符（{ming}）文案的唯一渲染入口，占位符写法同 liaoTian.tuPianWeiGui */
export function huoQuFanYiMiaoShu<T extends FanYiFenLei>(
  fenLei: T,
  jian: FanYiJian<T>,
  canShu: Readonly<Record<string, string | number>>,
): string {
  const muBan = fanYi[fenLei][jian] as string
  return muBan.replace(/\{(\w+)\}/g, (zheng, ming: string) =>
    Object.prototype.hasOwnProperty.call(canShu, ming) ? String(canShu[ming]) : zheng,
  )
}

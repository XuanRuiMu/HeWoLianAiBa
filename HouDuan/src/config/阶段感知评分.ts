export function 查基础分(行为: 行为键, 阶段: string): number {
  const 行 = 阶段感知评分表[行为]
  if (!行) return 0
  const 键 = 关系阶段顺序.includes(阶段 as 关系阶段名) ? (阶段 as 关系阶段名) : '冷淡'
  return 行[键]
}

export function 构建行为判定说明(): string[] {
  return [
    '【怎么判断这条消息】',
    ...行为顺序.map((行为) => `- ${行为}：${行为识别标准[行为]}`),
  ]
}

export function 构建当前阶段说明(阶段: string, 分数段: string): string[] {
  const 键 = 关系阶段顺序.includes(阶段 as 关系阶段名) ? (阶段 as 关系阶段名) : '冷淡'
  const 要点 = 阶段在意要点[键]
  return [
    `【此刻的关系：${键}（${分数段}）】`,
    `这个阶段最看重：${要点.最看重}`,
    `这个阶段不吃：${要点.不吃}`,
    `这个阶段还不到：${要点.还不到}`,
  ]
}

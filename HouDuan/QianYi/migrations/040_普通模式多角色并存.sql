-- 040：普通模式多角色并存（删除「同模式只能一个活跃角色」的设定）
--
-- 需求：普通模式允许同一用户同时生成并保留多个角色，多个角色的会话可并行聊天。
-- 变更：角色表上两个表达排他语义的部分唯一索引一并删除 ——
--       uk_角色_用户ID_活跃（迁移 004 建）与 uk_角色_用户ID_模式_活跃（迁移 010 建）。
--       只保留/建立非唯一的 idx_角色_用户ID_活跃，供「按用户取未封存角色」的查询使用；
--       唯一性约束删除后该索引的谓词与原来完全一致，仍是干净的覆盖索引。
--
-- 边界：挑战模式的「同一用户仅一局挑战进行中」**不变** —— 该约束由挑战对局表上的
--       uk_挑战对局_用户_进行中（迁移 010 建）表达，本迁移不触碰挑战对局/挑战积分两表。
--       角色表不再有排他索引后，挑战模式同一用户可以存在多个历史角色行，
--       但同时进行的对局仍由挑战对局表的唯一索引卡死。
--
-- 幂等：DROP INDEX IF EXISTS + CREATE INDEX IF NOT EXISTS，可重复执行、结果一致。
--
-- 标识符大小写：004/010 建这三个索引时索引名未加双引号，Postgres 会折叠为小写
--       （库内实际名为 uk_角色_用户id_模式_活跃 等）。因此下面同时给出「不加引号的折叠名」
--       与「加引号的原样名」两种 DROP 形态：折叠名命中所有由 004/010 建出来的实例，
--       原样名兜住任何以带引号形态建出这两个索引的实例，两者都带 IF EXISTS，互不干扰。

DROP INDEX IF EXISTS uk_角色_用户ID_活跃;
DROP INDEX IF EXISTS uk_角色_用户ID_模式_活跃;
DROP INDEX IF EXISTS "uk_角色_用户ID_活跃";
DROP INDEX IF EXISTS "uk_角色_用户ID_模式_活跃";

CREATE INDEX IF NOT EXISTS idx_角色_用户ID_活跃
    ON "角色"("用户ID") WHERE "封存" = FALSE AND "删除时间" IS NULL;

-- 053 删除已废弃的「系统表情」表
--
-- 背景：该表由 051_系统表情表.sql 建立，用于承载「联网收集的表情包库」元数据。
--        旧机制清理后，运行期表情包统一改由 表情包库.ts 从磁盘目录（表情包配置里的备份目录）
--        扫描并维护索引，候选、按短名查询、按 SHA256 查询全部走内存索引，
--        src 全域再无任何 SQL 语句读写该表 ⇒ 该表已成死表。
--
-- 删除对象（与 051 建立时逐一对应）：
--   1) 表本体 `系统表情`：ID / 短名 / 描述 / 情绪标签 / 适用场景 / SHA256 / MIME / 来源 / 启用 / 创建时间
--      （短名唯一约束随表消失，无需单独处理）
--   2) 部分索引 `系统表情_情绪标签_idx`（051 第 14 步建立）：随表一并删除，这里不单独 DROP INDEX，
--      避免在未建立该索引的库上报「索引不存在」
--   3) 表/列注释：随表一并消失，无需单独处理
--
-- 幂等：DROP TABLE IF EXISTS —— 表不存在（未执行 051、或已被清理）时本迁移为空操作，重复执行同样为空操作；
--       CASCADE 同时带走任何可能存在的依赖视图/外键，不依赖 051 的执行顺序。
--
-- 无任何对象以本表为外键目标（全库无 REFERENCES "系统表情"），故 CASCADE 实际不删任何用户数据；
-- 行级数据随表一并丢弃，不做备份。

DROP TABLE IF EXISTS "系统表情" CASCADE;
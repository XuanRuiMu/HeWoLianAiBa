-- 031 结局趣味文案快照列（FP-07 / 缺陷4）。
--
-- 根因：结局展示文案一直是「读取时现算」——库里三个结局列（角色.结局状态、游戏档案.结果类型、
--       游戏结局.结果状态）只存枚举键，没有任何文案列（F12）。这在过去无所谓，因为文案是枚举键的
--       确定性函数；但玩家要求结算时从趣味文案池**随机**抽一条，随机值一旦不落库就必然漂移：
--       同一局刷新一次换一句话，分享文案与战报海报各拿各的版本。故随机结果必须在结算那一刻钉成快照。
--
-- 为什么落在 角色 而不是 游戏结局（两表都存过结局，选错就得到一份会自相矛盾的快照）：
--   ① 语义对齐：游戏结局 的写入是 `ON CONFLICT ("用户ID","角色ID") DO NOTHING`（见 胜利失败条件.ts
--      的 xieRuYouXiJieJu 与结算事务内同一条 INSERT），即**只记首次结算、此后永不更新**；而
--      sheng_li_ai_qing 结算后 封存=false、可继续聊天=true，同一角色可被再次结算（例如之后好感度归零），
--      届时 角色.结局状态 与 游戏档案.结果类型 都会变成最新值，只有 游戏结局 停在第一次。
--      读取侧显示的是最新结局，快照若存在 游戏结局 就会与显示的结局对不上。
--   ② 零新连接：消息.ts::huoQuJiaoSeSuoYouZhe 本来就只查 角色；战绩.ts 两处查询已经
--      `LEFT JOIN "角色" r ON r."ID" = d."角色ID"`。快照放 角色 只是各多取一列，
--      放 游戏结局 则要为一次文案读取新增一条 JOIN/查询。
--   ③ 原子性：快照与 结局状态 由同一次结算写入（事务分支里在同一个 BEGIN/COMMIT 内），
--      不存在「有结局没快照」的中间态；快照缺失即等价于「趣味文案上线前的历史记录」。
--   ④ 为什么不塞进 游戏结局.摘要：摘要 JSON 全仓**只写不读**（唯一读者不存在），把玩家可见文本
--      埋进 JSON 既拿不到上面 ①②③ 的性质，又让文案变成不可索引、不可 CHECK 的暗值。
--
-- 存量数据：不回填。历史行没有「当时抽中了哪一句」的事实可考，回填等于伪造历史；
--            读取侧统一走 utils/结局.解析结局文案 的「快照优先、缺失回退确定性渲染」，
--            回退分支是确定性的，故旧记录不会随机漂移。
--
-- 幂等：ADD COLUMN IF NOT EXISTS + COMMENT ON 可重复执行；表不存在时整段跳过（只应用了部分增量的新库）。
-- 数据安全：纯增量 DDL，无 UPDATE/DELETE，不改任何既有列的类型、约束与默认值；
--          不触碰 030 建立的 ck_游戏结局_结果状态 CHECK，也不新增任何枚举键。

DO $q$
BEGIN
    IF to_regclass('public."角色"') IS NULL THEN
        RAISE NOTICE '031：本库尚无 角色 表，跳过 结局文案 列的创建';
        RETURN;
    END IF;

    ALTER TABLE "角色"
        ADD COLUMN IF NOT EXISTS "结局文案" TEXT;

    COMMENT ON COLUMN "角色"."结局文案" IS
        'FP-07 结局趣味文案快照：结算那一刻从 translations.jieGuoTongGuanChi/jieGuoShiBaiChi 随机抽中并代入他/她的成品句。只写枚举键的 结局状态/结果类型 与本列配对存在，读取侧快照优先、NULL 回退确定性渲染（NULL = 本列上线前的历史记录）';

    RAISE NOTICE '031：角色.结局文案 快照列已就位';
END
$q$;
